"""Build v3/data/kits.gen.js from the real characters in characters/.

run_v3.bat runs this before opening the game, so whatever FX Studio / Rig
Forge last saved is what V3 plays.  A page opened from disk can't read other
local files, so the kits are packed into one script that index.html loads
(window.PB3_KITS = {key: {...}}).

For each characters/<folder>/ with a character.json and a *.fxkit.json and at
least one enabled damaging effect, it keeps what V3 uses: the character.json
name / palette / stats / predicates, and from the FX file the timing, action
settings, effects, anchors, entry sets, paths, space, character scale,
palette LUT, dodge, movement style, targeting, unique ability and states.
Images are not packed.

Bodies: the test body characters/ual_swordsman/ual_swordsman.glb (v3/RIG_SPEC.md
section 8) is packed as base64 into v3/data/body.gen.js (window.PB3_BODY).
Every kit wears it, except a kit whose folder holds its own <folder>.glb
(kit "own_glb": true), which keeps its stand-in body for now.

Usage:  python v3/tools/build_kits.py   (paths are found from this file)
"""
import base64
import glob
import json
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
V3 = os.path.dirname(HERE)
ROOT = os.path.dirname(V3)
CHARS = os.path.join(ROOT, "characters")
OUT = os.path.join(V3, "data", "kits.gen.js")
BODY_GLB = os.path.join(CHARS, "ual_swordsman", "ual_swordsman.glb")
BODY_OUT = os.path.join(V3, "data", "body.gen.js")

FX_KEYS = ("timing", "action_settings", "effects", "anchors", "entry_sets", "paths", "space",
           "character_scale", "palette_lut", "dodge", "movement_style", "targeting", "unique_ability",
           "states", "retreat", "damaged", "aim", "fight_rhythm", "guard")
CH_KEYS = ("name", "display_name", "description", "predicates", "stats", "palette")


def load(path):
    with open(path, "r", encoding="utf-8") as f:
        return json.load(f)


def build():
    kits, skipped = {}, []
    for folder in sorted(os.listdir(CHARS)):
        d = os.path.join(CHARS, folder)
        if not os.path.isdir(d):
            continue
        ch_path = os.path.join(d, "character.json")
        fx_paths = glob.glob(os.path.join(d, "*.fxkit.json"))
        if not os.path.exists(ch_path) or not fx_paths:
            skipped.append((folder, "no character.json / FX file"))
            continue
        try:
            ch, fx = load(ch_path), load(fx_paths[0])
        except Exception as e:      # a broken file must not stop the game
            skipped.append((folder, "unreadable: %s" % e))
            continue
        effects = fx.get("effects") or []
        if not any(e.get("enabled", True) and (e.get("battle") or {}).get("deals_damage") for e in effects):
            skipped.append((folder, "no damaging effect"))
            continue
        key = folder.lower()
        kit = {"key": key, "folder": folder, "own_glb": os.path.exists(os.path.join(d, folder + ".glb"))}
        kit.update({k: ch.get(k) for k in CH_KEYS if k in ch})
        kit["fxkit"] = {k: fx.get(k) for k in FX_KEYS if k in fx}
        kits[key] = kit
    return kits, skipped


def main():
    kits, skipped = build()
    os.makedirs(os.path.dirname(OUT), exist_ok=True)
    body = json.dumps(kits, separators=(",", ":"), ensure_ascii=False)
    tmp = OUT + ".tmp"
    with open(tmp, "w", encoding="utf-8") as f:
        f.write("// Generated by v3/tools/build_kits.py from characters/ - do not edit.\n")
        f.write("window.PB3_KITS=" + body + ";\n")
    os.replace(tmp, OUT)
    print("V3 kits: %d characters -> %s (%d KB)" % (len(kits), os.path.relpath(OUT, ROOT), len(body) // 1024))
    write_body()
    for name, why in skipped:
        print("  skipped %s: %s" % (name, why))
    return 0


def write_body():
    """Pack the shared test body (a missing file = no body: every fighter keeps its stand-in)."""
    tmp = BODY_OUT + ".tmp"
    with open(tmp, "w", encoding="utf-8") as f:
        f.write("// Generated by v3/tools/build_kits.py from characters/ - do not edit.\n")
        if os.path.exists(BODY_GLB):
            with open(BODY_GLB, "rb") as g:
                data = base64.b64encode(g.read()).decode("ascii")
            name = os.path.splitext(os.path.basename(BODY_GLB))[0]
            f.write("window.PB3_BODY={name:%s,glb:\"%s\"};\n" % (json.dumps(name), data))
            print("V3 body: %s -> %s (%d KB)" % (name, os.path.relpath(BODY_OUT, ROOT), len(data) // 1024))
        else:
            f.write("window.PB3_BODY=null;\n")
            print("V3 body: %s not found - stand-in bodies" % os.path.relpath(BODY_GLB, ROOT))
    os.replace(tmp, BODY_OUT)


if __name__ == "__main__":
    sys.exit(main())
